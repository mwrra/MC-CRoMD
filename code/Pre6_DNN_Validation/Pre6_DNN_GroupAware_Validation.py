def find_existing_file(folder: Path, stem: str) -> Path:
    candidates = (
        folder / f"{stem}.csv.gz",
        folder / f"{stem}.csv",
        folder / f"{stem}.xlsx",
    )
    for candidate in candidates:
        if candidate.exists():
            return candidate
    raise FileNotFoundError(
        "Could not find any of:\n" + "\n".join(str(p) for p in candidates)
    )


def read_table(path: Path) -> pd.DataFrame:
    suffixes = "".join(path.suffixes).lower()
    if suffixes.endswith(".csv.gz") or path.suffix.lower() == ".csv":
        return pd.read_csv(path)
    if path.suffix.lower() in {".xlsx", ".xlsm", ".xls"}:
        return pd.read_excel(path)
    raise ValueError(f"Unsupported file format: {path}")


def load_feature_names_json(scenario_dir: Path) -> list[str]:
    path = scenario_dir / "Feature_Names.json"
    if not path.exists():
        raise FileNotFoundError(f"Feature_Names.json not found:\n{path}")
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, list) or not all(isinstance(x, str) for x in data):
        raise ValueError(f"Feature_Names.json must be a JSON list of strings: {path}")
    names = [x.strip() for x in data]
    if len(names) != len(set(names)):
        raise ValueError(f"Duplicate feature names found in {path}")
    return names


def load_npy_split(
    preprocessing_dir: Path,
    scenario: str,
    split_name: str,
) -> tuple[np.ndarray, pd.DataFrame, list[str]]:
    if split_name not in {"Train", "Validation"}:
        raise ValueError(
            "This program permits only Train and Validation. "
            "Test is intentionally prohibited."
        )

    scenario_dir = preprocessing_dir / scenario
    split_dir = scenario_dir / SOURCE_VARIANT / split_name
    x_path = split_dir / "X.npy"
    metadata_path = split_dir / "Metadata.csv.gz"

    if not x_path.exists():
        raise FileNotFoundError(f"X.npy not found:\n{x_path}")
    if not metadata_path.exists():
        raise FileNotFoundError(f"Metadata.csv.gz not found:\n{metadata_path}")

    feature_names = load_feature_names_json(scenario_dir)
    X = np.load(x_path, mmap_mode="r")
    metadata = pd.read_csv(metadata_path)
    metadata.columns = [str(c).strip() for c in metadata.columns]

    if TARGET_COLUMN not in metadata.columns:
        raise KeyError(f"{scenario}/{split_name}: missing metadata column {TARGET_COLUMN!r}")
    if X.ndim != 2:
        raise ValueError(f"{scenario}/{split_name}: X.npy must be 2-D, got shape {X.shape}")
    if X.shape[0] != len(metadata):
        raise ValueError(
            f"{scenario}/{split_name}: row mismatch between X.npy ({X.shape[0]}) "
            f"and Metadata.csv.gz ({len(metadata)})."
        )
    if X.shape[1] != len(feature_names):
        raise ValueError(
            f"{scenario}/{split_name}: feature-count mismatch between X.npy ({X.shape[1]}) "
            f"and Feature_Names.json ({len(feature_names)})."
        )

    return X, metadata, feature_names


def load_standard_split(
    preprocessing_dir: Path,
    scenario: str,
    split_name: str,
) -> pd.DataFrame:
    if split_name not in {"Train", "Validation"}:
        raise ValueError(
            "This program permits only Train and Validation. "
            "Test is intentionally prohibited."
        )

    folder = preprocessing_dir / scenario / SOURCE_VARIANT
    path = find_existing_file(folder, split_name)
    frame = read_table(path)
    frame.columns = [str(c).strip() for c in frame.columns]

    required = {TARGET_COLUMN}
    missing = required.difference(frame.columns)
    if missing:
        raise KeyError(f"{scenario}/{split_name}: missing columns {sorted(missing)}")

    return frame


def read_selected_features(
    feature_selection_dir: Path,
    scenario: str,
    method: str,
    k: int,
) -> list[str]:
    path = (
        feature_selection_dir
        / scenario
        / method
        / f"Selected_Features_K{k:03d}.xlsx"
    )
    if not path.exists():
        raise FileNotFoundError(
            f"Selected feature file does not exist:\n{path}"
        )

    frame = pd.read_excel(path)
    if "Feature" not in frame.columns:
        raise KeyError(f"'Feature' column not found in {path}")

    features = frame["Feature"].dropna().astype(str).str.strip().tolist()
    features = [x for x in features if x]

    if len(features) != k:
        raise ValueError(
            f"{scenario}/{method}/K{k}: selected feature file contains "
            f"{len(features)} features, expected exactly {k}."
        )

    if len(set(features)) != len(features):
        raise ValueError(
            f"{scenario}/{method}/K{k}: duplicate feature names were found."
        )

    return features


def validate_features_exist(
    frame: pd.DataFrame,
    features: list[str],
    context: str,
) -> None:
    missing = sorted(set(features).difference(frame.columns))
    if missing:
        raise KeyError(
            f"{context}: {len(missing)} selected features are absent. "
            f"Examples: {missing[:10]}"
        )


def choose_sample_id_column(frame: pd.DataFrame) -> str | None:
    for column in ("ImageSHA256", "FileName", "ImgName"):
        if column in frame.columns:
            return column
    return None


