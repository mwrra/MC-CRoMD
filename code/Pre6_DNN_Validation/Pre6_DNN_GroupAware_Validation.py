def build_candidate_feature_configs(
    classical_checkpoint: Path,
    top_n: int,
) -> tuple[pd.DataFrame, dict[str, list[tuple[str, int]]]]:
    """
    Select top-N feature configurations per scenario by aggregate Screening
    performance across ALL nine classical models.

    This is a validation-only pre-screening step. Test is not involved.
    """
    if not classical_checkpoint.exists():
        raise FileNotFoundError(
            f"Classical Pre6 checkpoint not found:\n{classical_checkpoint}"
        )

    df = pd.read_csv(classical_checkpoint)

    required = {
        "Stage",
        "Scenario",
        "Feature_Method",
        "K",
        "Model",
        "Status",
        "Validation_Accuracy",
        "Validation_F1_Macro",
    }
    missing = required.difference(df.columns)
    if missing:
        raise KeyError(
            f"Classical checkpoint is missing columns: {sorted(missing)}"
        )

    screening = df[
        df["Stage"].astype(str).str.strip().eq("Screening")
        & df["Status"].astype(str).str.strip().eq("Completed")
        & df["Scenario"].astype(str).str.strip().isin(SCENARIOS)
    ].copy()

    if screening.empty:
        raise RuntimeError("No completed classical Screening rows were found.")

    screening["K"] = pd.to_numeric(screening["K"], errors="raise").astype(int)
    screening["Validation_Accuracy"] = pd.to_numeric(
        screening["Validation_Accuracy"], errors="coerce"
    )
    screening["Validation_F1_Macro"] = pd.to_numeric(
        screening["Validation_F1_Macro"], errors="coerce"
    )

    screening = screening.dropna(
        subset=["Validation_Accuracy", "Validation_F1_Macro"]
    )

    models_present = set(screening["Model"].astype(str).str.strip().unique())
    missing_models = EXPECTED_CLASSICAL_MODELS.difference(models_present)
    if missing_models:
        raise RuntimeError(
            "Classical Screening is incomplete. Missing expected models: "
            + ", ".join(sorted(missing_models))
        )

    rows: list[dict[str, Any]] = []
    selected: dict[str, list[tuple[str, int]]] = {}

    for scenario in SCENARIOS:
        part = screening[
            screening["Scenario"].astype(str).str.strip().eq(scenario)
        ].copy()

        if part.empty:
            raise RuntimeError(f"No Screening rows for scenario: {scenario}")

        grouped = (
            part.groupby(["Feature_Method", "K"], as_index=False)
            .agg(
                Classical_Model_Count=("Model", "nunique"),
                Mean_Screening_Accuracy=("Validation_Accuracy", "mean"),
                Mean_Screening_F1_Macro=("Validation_F1_Macro", "mean"),
                Min_Screening_Accuracy=("Validation_Accuracy", "min"),
                Max_Screening_Accuracy=("Validation_Accuracy", "max"),
            )
        )

        # Only compare configurations evaluated by all expected models.
        grouped = grouped[
            grouped["Classical_Model_Count"] == len(EXPECTED_CLASSICAL_MODELS)
        ].copy()

        if grouped.empty:
            raise RuntimeError(
                f"{scenario}: no feature configuration has complete Screening "
                f"results for all {len(EXPECTED_CLASSICAL_MODELS)} classical models."
            )

        grouped = grouped.sort_values(
            [
                "Mean_Screening_Accuracy",
                "Mean_Screening_F1_Macro",
                "K",
                "Feature_Method",
            ],
            ascending=[False, False, True, True],
            kind="mergesort",
        ).reset_index(drop=True)

        grouped.insert(0, "Scenario", scenario)
        grouped.insert(1, "Aggregate_Rank", np.arange(1, len(grouped) + 1))
        grouped["Selected_For_DNN"] = grouped["Aggregate_Rank"] <= top_n

        top = grouped.head(top_n)
        selected[scenario] = [
            (str(row.Feature_Method), int(row.K))
            for row in top.itertuples(index=False)
        ]

        rows.extend(grouped.to_dict("records"))

    all_candidates = pd.DataFrame(rows)
    return all_candidates, selected


