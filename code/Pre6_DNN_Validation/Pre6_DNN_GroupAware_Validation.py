def run_one_seed(
    *,
    scenario: str,
    method: str,
    k: int,
    seed: int,
    train_frame: pd.DataFrame | None,
    validation_frame: pd.DataFrame | None,
    selected_features: list[str],
    run_dir: Path,
    train_matrix: np.ndarray | None = None,
    validation_matrix: np.ndarray | None = None,
    train_metadata: pd.DataFrame | None = None,
    validation_metadata: pd.DataFrame | None = None,
    feature_names: list[str] | None = None,
) -> dict[str, Any]:
    set_global_seed(seed)
    tf.keras.backend.clear_session()
    gc.collect()

    using_npy = train_matrix is not None

    if using_npy:
        if any(x is None for x in (validation_matrix, train_metadata, validation_metadata, feature_names)):
            raise ValueError("Incomplete NPY-backed inputs for run_one_seed.")
        feature_index = {name: i for i, name in enumerate(feature_names)}
        missing = [f for f in selected_features if f not in feature_index]
        if missing:
            raise KeyError(
                f"{scenario}/{method}/K{k}: {len(missing)} selected features are absent from "
                f"Feature_Names.json. Examples: {missing[:10]}"
            )
        selected_idx = np.asarray([feature_index[f] for f in selected_features], dtype=np.int64)
        label_encoder = LabelEncoder()
        y_train = label_encoder.fit_transform(train_metadata[TARGET_COLUMN].to_numpy())
        y_val = label_encoder.transform(validation_metadata[TARGET_COLUMN].to_numpy())
        X_train = np.asarray(train_matrix[:, selected_idx], dtype=np.float32)
        X_val = np.asarray(validation_matrix[:, selected_idx], dtype=np.float32)
        train_rows = len(train_metadata)
        validation_rows = len(validation_metadata)
        sample_source = validation_metadata
    else:
        if train_frame is None or validation_frame is None:
            raise ValueError("DataFrame-backed inputs are missing.")
        validate_features_exist(
            train_frame,
            selected_features,
            f"{scenario}/{method}/K{k}/Train",
        )
        validate_features_exist(
            validation_frame,
            selected_features,
            f"{scenario}/{method}/K{k}/Validation",
        )
        label_encoder = LabelEncoder()
        y_train = label_encoder.fit_transform(train_frame[TARGET_COLUMN].to_numpy())
        y_val = label_encoder.transform(validation_frame[TARGET_COLUMN].to_numpy())
        X_train = train_frame[selected_features].to_numpy(dtype=np.float32)
        X_val = validation_frame[selected_features].to_numpy(dtype=np.float32)
        train_rows = len(train_frame)
        validation_rows = len(validation_frame)
        sample_source = validation_frame

    classes_train = set(np.unique(y_train))
    classes_val = set(np.unique(y_val))
    if not classes_val.issubset(classes_train):
        raise ValueError(
            f"{scenario}: Validation contains a class absent from Train."
        )

    n_classes = len(label_encoder.classes_)

    if not np.isfinite(X_train).all():
        raise ValueError(
            f"{scenario}/{method}/K{k}: Train contains NaN or infinity "
            "after preprocessing."
        )
    if not np.isfinite(X_val).all():
        raise ValueError(
            f"{scenario}/{method}/K{k}: Validation contains NaN or infinity "
            "after preprocessing."
        )

    run_dir.mkdir(parents=True, exist_ok=True)
    best_model_path = run_dir / "Best_Model.keras"

    model = build_dnn(
        input_dim=len(selected_features),
        n_classes=n_classes,
    )

    callbacks = [
        keras.callbacks.EarlyStopping(
            monitor="val_loss",
            patience=EARLY_STOPPING_PATIENCE,
            mode="min",
            restore_best_weights=True,
            verbose=1,
        ),
        keras.callbacks.ReduceLROnPlateau(
            monitor="val_loss",
            factor=REDUCE_LR_FACTOR,
            patience=REDUCE_LR_PATIENCE,
            min_lr=MIN_LEARNING_RATE,
            mode="min",
            verbose=1,
        ),
        keras.callbacks.ModelCheckpoint(
            filepath=best_model_path,
            monitor="val_loss",
            mode="min",
            save_best_only=True,
            save_weights_only=False,
            verbose=0,
        ),
        keras.callbacks.TerminateOnNaN(),
    ]

    fit_start = time.perf_counter()
    history = model.fit(
        X_train,
        y_train,
        validation_data=(X_val, y_val),
        epochs=MAX_EPOCHS,
        batch_size=BATCH_SIZE,
        shuffle=True,
        callbacks=callbacks,
        verbose=2,
    )
    fit_seconds = time.perf_counter() - fit_start

    # Reload the exact checkpoint with minimum validation loss.
    best_model = keras.models.load_model(best_model_path)

    predict_start = time.perf_counter()
    y_pred, probabilities = predict_labels_and_probabilities(
        best_model,
        X_val,
        n_classes=n_classes,
    )
    predict_seconds = time.perf_counter() - predict_start

    metrics = calculate_metrics(
        y_true=y_val,
        y_pred=y_pred,
        probabilities=probabilities,
        n_classes=n_classes,
    )

    val_losses = np.asarray(history.history["val_loss"], dtype=float)
    best_epoch = int(np.nanargmin(val_losses)) + 1
    best_val_loss = float(np.nanmin(val_losses))

    # Save history.
    history_frame = pd.DataFrame(history.history)
    history_frame.index = np.arange(1, len(history_frame) + 1)
    history_frame.index.name = "Epoch"
    history_frame.to_csv(run_dir / "Training_History.csv")

    # Save confusion matrix counts.
    cm = confusion_matrix(
        y_val,
        y_pred,
        labels=np.arange(n_classes),
    )
    class_names = [str(x) for x in label_encoder.classes_]
    pd.DataFrame(
        cm,
        index=[f"True_{x}" for x in class_names],
        columns=[f"Pred_{x}" for x in class_names],
    ).to_excel(run_dir / "Validation_Confusion_Matrix.xlsx")

    # Save per-sample predictions/probabilities.
    sample_id_column = choose_sample_id_column(sample_source)
    prediction_frame = pd.DataFrame(
        {
            "Row_Index": sample_source.index.to_numpy(),
            "True_Encoded": y_val,
            "Predicted_Encoded": y_pred,
            "True_Label": [class_names[i] for i in y_val],
            "Predicted_Label": [class_names[i] for i in y_pred],
        }
    )
    if sample_id_column is not None:
        prediction_frame.insert(
            1,
            sample_id_column,
            sample_source[sample_id_column].astype(str).to_numpy(),
        )

    for class_index, class_name in enumerate(class_names):
        prediction_frame[f"Probability_{class_name}"] = probabilities[:, class_index]

    prediction_frame.to_csv(
        run_dir / "Validation_Predictions.csv",
        index=False,
    )

    # Save selected feature list.
    pd.DataFrame(
        {
            "Rank": np.arange(1, len(selected_features) + 1),
            "Feature": selected_features,
        }
    ).to_excel(run_dir / "Selected_Features.xlsx", index=False)

    # Save architecture summary.
    lines: list[str] = []
    best_model.summary(print_fn=lines.append)
    (run_dir / "Model_Summary.txt").write_text(
        "\n".join(lines),
        encoding="utf-8",
    )

    model_config = {
        "scenario": scenario,
        "feature_method": method,
        "k": k,
        "seed": seed,
        "source_variant": SOURCE_VARIANT,
        "architecture": {
            "dense_units": list(DENSE_UNITS),
            "activations": ["relu", "relu", "relu"],
            "batch_normalization_after": [128, 64],
            "dropout_rates": list(DROPOUT_RATES),
            "output_units": 1 if n_classes == 2 else n_classes,
            "output_activation": "sigmoid" if n_classes == 2 else "softmax",
            "kernel_initializer": "he_normal",
        },
        "training": {
            "optimizer": "Adam",
            "initial_learning_rate": INITIAL_LEARNING_RATE,
            "loss": (
                "binary_crossentropy"
                if n_classes == 2
                else "sparse_categorical_crossentropy"
            ),
            "batch_size": BATCH_SIZE,
            "max_epochs": MAX_EPOCHS,
            "shuffle": True,
            "early_stopping": {
                "monitor": "val_loss",
                "patience": EARLY_STOPPING_PATIENCE,
                "mode": "min",
                "restore_best_weights": True,
            },
            "reduce_lr_on_plateau": {
                "monitor": "val_loss",
                "factor": REDUCE_LR_FACTOR,
                "patience": REDUCE_LR_PATIENCE,
                "min_lr": MIN_LEARNING_RATE,
                "mode": "min",
            },
            "checkpoint": {
                "monitor": "val_loss",
                "mode": "min",
                "save_best_only": True,
            },
        },
        "class_names": class_names,
        "parameter_count": int(best_model.count_params()),
        "best_epoch_by_val_loss": best_epoch,
        "best_val_loss": best_val_loss,
    }
    json_dump(run_dir / "Run_Metadata.json", model_config)

    result: dict[str, Any] = {
        "Run_ID": make_run_id(scenario, method, k, seed),
        "Scenario": scenario,
        "Feature_Method": method,
        "K": int(k),
        "Seed": int(seed),
        "Train_Rows": int(train_rows),
        "Validation_Rows": int(validation_rows),
        "Feature_Count": int(len(selected_features)),
        "Class_Count": int(n_classes),
        "Class_Names_JSON": json.dumps(class_names, ensure_ascii=False),
        "Epochs_Ran": int(len(history_frame)),
        "Best_Epoch_By_Val_Loss": best_epoch,
        "Best_Val_Loss": best_val_loss,
        "Fit_Seconds": float(fit_seconds),
        "Predict_Seconds": float(predict_seconds),
        "Parameter_Count": int(best_model.count_params()),
        "Status": "Completed",
        "Error": "",
    }
    result.update(metrics)

    del model, best_model, X_train, X_val, y_train, y_val, y_pred, probabilities
    tf.keras.backend.clear_session()
    gc.collect()

    return result


