def load_dnn_checkpoint(path: Path) -> pd.DataFrame:
    if not path.exists():
        return pd.DataFrame(columns=RESULT_COLUMNS)

    frame = pd.read_csv(path)
    for column in RESULT_COLUMNS:
        if column not in frame.columns:
            frame[column] = np.nan
    return frame[RESULT_COLUMNS]


def save_dnn_checkpoint(frame: pd.DataFrame, path: Path) -> None:
    temp = path.with_name(path.stem + "_TEMP.csv")
    frame.to_csv(temp, index=False)
    temp.replace(path)


def upsert_checkpoint_row(
    checkpoint: pd.DataFrame,
    row: dict[str, Any],
    path: Path,
) -> pd.DataFrame:
    run_id = str(row["Run_ID"])
    checkpoint = checkpoint[
        checkpoint["Run_ID"].astype(str) != run_id
    ].copy()
    checkpoint = pd.concat(
        [checkpoint, pd.DataFrame([row], columns=RESULT_COLUMNS)],
        ignore_index=True,
    )
    save_dnn_checkpoint(checkpoint, path)
    return checkpoint


def completed_run_ids(checkpoint: pd.DataFrame) -> set[str]:
    if checkpoint.empty:
        return set()
    return set(
        checkpoint.loc[
            checkpoint["Status"].astype(str).eq("Completed"),
            "Run_ID",
        ].astype(str)
    )


def time_limit_reached(start_time: float, max_hours: float) -> bool:
    if max_hours <= 0:
        return False
    return (time.perf_counter() - start_time) >= max_hours * 3600.0


