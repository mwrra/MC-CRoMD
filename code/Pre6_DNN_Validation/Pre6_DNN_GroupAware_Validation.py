def create_validation_reports(
    checkpoint: pd.DataFrame,
    all_candidates: pd.DataFrame,
    selected_candidates: dict[str, list[tuple[str, int]]],
    seeds: tuple[int, ...],
    output_dir: Path,
) -> None:
    completed = checkpoint[
        checkpoint["Status"].astype(str).eq("Completed")
    ].copy()

    if completed.empty:
        return

    # Save raw completed runs.
    completed.sort_values(
        ["Scenario", "Feature_Method", "K", "Seed"]
    ).to_excel(
        output_dir / "All_DNN_Validation_Runs.xlsx",
        index=False,
    )

    expected_run_count = sum(
        len(configs) * len(seeds)
        for configs in selected_candidates.values()
    )

    if len(completed) < expected_run_count:
        # Partial reports are still useful, but do not declare a final best config.
        partial = (
            completed.groupby(
                ["Scenario", "Feature_Method", "K"],
                as_index=False,
            )
            .agg(
                Completed_Seeds=("Seed", "nunique"),
                Mean_Validation_Accuracy=("Validation_Accuracy", "mean"),
                SD_Validation_Accuracy=("Validation_Accuracy", "std"),
                Mean_Validation_F1_Macro=("Validation_F1_Macro", "mean"),
                SD_Validation_F1_Macro=("Validation_F1_Macro", "std"),
            )
        )
        partial.to_excel(
            output_dir / "DNN_Validation_Summary_PARTIAL.xlsx",
            index=False,
        )
        return

    # Require exact prespecified seed set for every selected configuration.
    expected_seed_set = set(seeds)
    for scenario, configs in selected_candidates.items():
        for method, k in configs:
            subset = completed[
                (completed["Scenario"] == scenario)
                & (completed["Feature_Method"] == method)
                & (completed["K"].astype(int) == int(k))
            ]
            got = set(pd.to_numeric(subset["Seed"], errors="coerce").dropna().astype(int))
            if got != expected_seed_set:
                raise RuntimeError(
                    f"Incomplete seed set for {scenario}/{method}/K{k}. "
                    f"Expected {sorted(expected_seed_set)}, got {sorted(got)}."
                )

    summary = (
        completed.groupby(
            ["Scenario", "Feature_Method", "K"],
            as_index=False,
        )
        .agg(
            Seeds=("Seed", "nunique"),
            Mean_Validation_Accuracy=("Validation_Accuracy", "mean"),
            SD_Validation_Accuracy=("Validation_Accuracy", "std"),
            Mean_Validation_Precision_Macro=("Validation_Precision_Macro", "mean"),
            Mean_Validation_Recall_Macro=("Validation_Recall_Macro", "mean"),
            Mean_Validation_F1_Macro=("Validation_F1_Macro", "mean"),
            SD_Validation_F1_Macro=("Validation_F1_Macro", "std"),
            Mean_Validation_F1_Weighted=("Validation_F1_Weighted", "mean"),
            Mean_Validation_ROC_AUC_OVR_Macro=("Validation_ROC_AUC_OVR_Macro", "mean"),
            Mean_Fit_Seconds=("Fit_Seconds", "mean"),
            Mean_Predict_Seconds=("Predict_Seconds", "mean"),
            Mean_Epochs_Ran=("Epochs_Ran", "mean"),
        )
    )

    summary = summary.sort_values(
        [
            "Scenario",
            PRIMARY_SELECTION_METRIC,
            SECONDARY_SELECTION_METRIC,
            "K",
            "Feature_Method",
        ],
        ascending=[True, False, False, True, True],
        kind="mergesort",
    )

    summary.to_excel(
        output_dir / "DNN_Validation_Summary.xlsx",
        index=False,
    )

    best_rows: list[pd.Series] = []
    for scenario in SCENARIOS:
        part = summary[summary["Scenario"] == scenario].copy()
        if part.empty:
            raise RuntimeError(f"No completed DNN summary for {scenario}.")
        best_rows.append(part.iloc[0])

    best = pd.DataFrame(best_rows)
    best.to_excel(
        output_dir / "Best_DNN_Configuration_Per_Scenario.xlsx",
        index=False,
    )

    # Save a compact candidate audit tying classical pre-screening to DNN runs.
    all_candidates.to_excel(
        output_dir / "Classical_Screening_Aggregate_For_DNN.xlsx",
        index=False,
    )


