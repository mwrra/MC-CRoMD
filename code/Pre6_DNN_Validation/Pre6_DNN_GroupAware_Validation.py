# -*- coding: utf-8 -*-
"""
Pre6_DNN_GroupAware_Validation.py

Leakage-controlled DNN validation for the revised MC-CRoMD workflow.

Scientific policy
-----------------
1) Uses ONLY the already-created group-aware Train and Validation partitions.
2) NEVER loads or uses Test in this program.
3) Uses StandardScaled data generated by Pre4; no scaler is refitted here.
   Patch size 32 is read from Pre4 low-memory X.npy + Metadata.csv.gz storage.
4) Candidate feature configurations are pre-screened using ONLY the completed
   classical-model Screening results in Validation_Checkpoint.csv:
      - aggregate mean Validation Accuracy across all completed classical models
      - tie-break by mean Validation F1-Macro
      - final tie-break by smaller K (parsimony)
   The top-N unique (Feature_Method, K) configurations per scenario are then
   evaluated by the DNN.
5) DNN architecture and training hyperparameters are fixed a priori.
6) Each candidate configuration is repeated using prespecified random seeds
   (default: 42, 43, 44) to reduce dependence on a single stochastic run.
7) Final DNN configuration selection uses the MEAN validation performance
   across the prespecified seeds. No seed is cherry-picked.
8) Early stopping and model checkpointing monitor val_loss only.
9) Test remains locked for a separate final-test program after all model and
   feature-configuration decisions are frozen.
10) Per-sample validation predictions/probabilities, confusion matrices,
    histories, model files, and metadata are saved for reproducibility.

Default architecture
--------------------
Input
 -> Dense(128, ReLU)
 -> BatchNormalization
 -> Dropout(0.30)
 -> Dense(64, ReLU)
 -> BatchNormalization
 -> Dropout(0.20)
 -> Dense(32, ReLU)
 -> Binary: Dense(1, sigmoid)
    Multi-class: Dense(n_classes, softmax)

Optimizer       : Adam
Initial LR      : 0.001
Batch size      : 64
Max epochs      : 100
Early stopping  : monitor=val_loss, patience=15, restore_best_weights=True
Reduce LR       : monitor=val_loss, factor=0.5, patience=5, min_lr=1e-6
Checkpoint      : best val_loss
Selection       : mean Validation Accuracy, then mean Macro-F1, then smaller K
Seeds           : 42, 43, 44

Run example
-----------
python Pre6_DNN_GroupAware_Validation.py --patch-size 64
python Pre6_DNN_GroupAware_Validation.py --patch-size 128
python Pre6_DNN_GroupAware_Validation.py --patch-size 256
python Pre6_DNN_GroupAware_Validation.py --patch-size 32

IMPORTANT:
- Pre4, Pre5, and classical Pre6 Screening must already be complete for the
  requested patch size.
- This script intentionally refuses to read Test.
"""

