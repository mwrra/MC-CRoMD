def build_dnn(input_dim: int, n_classes: int) -> keras.Model:
    if input_dim <= 0:
        raise ValueError("input_dim must be positive.")
    if n_classes < 2:
        raise ValueError("n_classes must be at least 2.")

    inputs = keras.Input(shape=(input_dim,), name="features")
    x = layers.Dense(
        DENSE_UNITS[0],
        activation="relu",
        kernel_initializer="he_normal",
        name="dense_128",
    )(inputs)
    x = layers.BatchNormalization(name="bn_128")(x)
    x = layers.Dropout(DROPOUT_RATES[0], name="dropout_030")(x)

    x = layers.Dense(
        DENSE_UNITS[1],
        activation="relu",
        kernel_initializer="he_normal",
        name="dense_64",
    )(x)
    x = layers.BatchNormalization(name="bn_64")(x)
    x = layers.Dropout(DROPOUT_RATES[1], name="dropout_020")(x)

    x = layers.Dense(
        DENSE_UNITS[2],
        activation="relu",
        kernel_initializer="he_normal",
        name="dense_32",
    )(x)

    if n_classes == 2:
        outputs = layers.Dense(1, activation="sigmoid", name="output")(x)
        loss = "binary_crossentropy"
    else:
        outputs = layers.Dense(
            n_classes,
            activation="softmax",
            name="output",
        )(x)
        loss = "sparse_categorical_crossentropy"

    model = keras.Model(inputs=inputs, outputs=outputs, name="MC_CRoMD_DNN")

    optimizer = keras.optimizers.Adam(
        learning_rate=INITIAL_LEARNING_RATE
    )

    model.compile(
        optimizer=optimizer,
        loss=loss,
        metrics=[keras.metrics.SparseCategoricalAccuracy(name="accuracy")]
        if n_classes > 2
        else [keras.metrics.BinaryAccuracy(name="accuracy", threshold=0.5)],
    )

    return model


def predict_labels_and_probabilities(
    model: keras.Model,
    X: np.ndarray,
    n_classes: int,
) -> tuple[np.ndarray, np.ndarray]:
    raw = np.asarray(model.predict(X, verbose=0), dtype=float)

    if n_classes == 2:
        positive = raw.reshape(-1)
        probabilities = np.column_stack([1.0 - positive, positive])
        predictions = (positive >= 0.5).astype(int)
    else:
        probabilities = raw
        predictions = np.argmax(probabilities, axis=1).astype(int)

    return predictions, probabilities


def calculate_metrics(
    y_true: np.ndarray,
    y_pred: np.ndarray,
    probabilities: np.ndarray,
    n_classes: int,
) -> dict[str, float]:
    metrics = {
        "Validation_Accuracy": float(accuracy_score(y_true, y_pred)),
        "Validation_Precision_Macro": float(
            precision_score(y_true, y_pred, average="macro", zero_division=0)
        ),
        "Validation_Recall_Macro": float(
            recall_score(y_true, y_pred, average="macro", zero_division=0)
        ),
        "Validation_F1_Macro": float(
            f1_score(y_true, y_pred, average="macro", zero_division=0)
        ),
        "Validation_Precision_Weighted": float(
            precision_score(y_true, y_pred, average="weighted", zero_division=0)
        ),
        "Validation_Recall_Weighted": float(
            recall_score(y_true, y_pred, average="weighted", zero_division=0)
        ),
        "Validation_F1_Weighted": float(
            f1_score(y_true, y_pred, average="weighted", zero_division=0)
        ),
    }

    try:
        if n_classes == 2:
            auc_value = roc_auc_score(y_true, probabilities[:, 1])
        else:
            y_bin = label_binarize(y_true, classes=np.arange(n_classes))
            auc_value = roc_auc_score(
                y_bin,
                probabilities,
                average="macro",
                multi_class="ovr",
            )
        metrics["Validation_ROC_AUC_OVR_Macro"] = float(auc_value)
    except Exception:
        metrics["Validation_ROC_AUC_OVR_Macro"] = float("nan")

    return metrics


